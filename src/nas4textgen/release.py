"""The checksum manifest a tagged revision is cited by.

A deposit in an archive was considered and decided against: the analysis code and the data
it reads move together, so a reader who clones the tag gets a tree in which every command in
the reproducibility section runs against the artifacts the paper reports. What an archive
would have supplied and a git tag does not is a guarantee that the bytes have not changed,
and that is what this file restores.

**Checksums, not sizes or dates.** A file can be replaced with one of the same length on the
same day. SHA-256 over the content is the only claim worth making, and it is cheap.

**Generated, never hand-listed.** A manifest typed by hand is a list of the files somebody
remembered, and the one that matters is the one they forgot.
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass
from pathlib import Path

#: What the paper cites and a reader needs to re-derive it. Directories are walked; a
#: pattern that matches nothing is reported rather than skipped, because an artifact that
#: silently stopped being produced is exactly what a manifest is for.
PUBLISHED = (
    "artifacts/benchmark/table.csv",
    "artifacts/benchmark/summary.json",
    "artifacts/space/enumeration.csv",
    "artifacts/space/enumeration_summary.json",
    "artifacts/characterisation",
    "artifacts/surrogate",
    "artifacts/search",
    "artifacts/sampling",
    "artifacts/transfer/analysis.json",
    "artifacts/battery/analysis.json",
    "artifacts/references/verification.json",
    "artifacts/audit/prior_protocol.json",
    "artifacts/campaign/cost.json",
    "artifacts/campaign/progress.json",
    "artifacts/manifests/runs.jsonl",
    "artifacts/replication/manifest.json",
    "artifacts/image/published.json",
)

#: The file the manifest is written to, inside the repository and therefore inside the tag.
MANIFEST = "artifacts/release/checksums.txt"


class NothingToPublish(RuntimeError):
    """Raised when none of the published paths exist."""


@dataclass(frozen=True)
class Entry:
    """One published file and its digest."""

    path: str
    sha256: str
    bytes: int

    def as_line(self) -> str:
        # The format `sha256sum --check` reads, so verifying needs no tool from this
        # project: `sha256sum -c checksums.txt` from the repository root.
        return f"{self.sha256}  {self.path}"


def digest(path: Path, chunk: int = 1 << 20) -> str:
    sha = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(chunk), b""):
            sha.update(block)
    return sha.hexdigest()


def collect(root: Path, published: tuple[str, ...] = PUBLISHED
            ) -> tuple[list[Entry], list[str]]:
    """Every published file with its digest, and any declared path that does not exist."""
    entries: list[Entry] = []
    absent: list[str] = []
    for relative in published:
        target = root / relative
        if target.is_dir():
            found = sorted(p for p in target.rglob("*") if p.is_file())
            if not found:
                absent.append(relative)
            for path in found:
                entries.append(Entry(path=str(path.relative_to(root)),
                                     sha256=digest(path),
                                     bytes=path.stat().st_size))
        elif target.is_file():
            entries.append(Entry(path=relative, sha256=digest(target),
                                 bytes=target.stat().st_size))
        else:
            absent.append(relative)
    return sorted(entries, key=lambda e: e.path), absent


def render(entries: list[Entry], absent: list[str]) -> str:
    """The manifest, in the format `sha256sum --check` reads."""
    total = sum(e.bytes for e in entries)
    lines = [
        "# SHA-256 of every artifact this paper cites, at the tagged revision that holds",
        "# them. Verify from the repository root with:",
        "#",
        "#     sha256sum -c artifacts/release/checksums.txt",
        "#",
        f"# {len(entries)} files, {total / 1e6:.1f} MB. Generated by",
        "# `python -m nas4textgen.cli release`; do not edit.",
    ]
    if absent:
        lines += [
            "#",
            "# Declared and not present at generation time — each is a stage that has not",
            "# run in this checkout, and a reader cloning the tag will not find it:",
            *(f"#   {path}" for path in absent),
        ]
    # No blank line before the entries: `shasum -c` on macOS reports one as improperly
    # formatted, and a verification command that prints a warning is one a reader stops
    # trusting the output of.
    lines.extend(entry.as_line() for entry in entries)
    return "\n".join(lines) + "\n"


def write(root: Path) -> tuple[Path, list[Entry], list[str]]:
    """Generate the manifest and put it where the tag will carry it."""
    entries, absent = collect(root)
    if not entries:
        raise NothingToPublish(
            "none of the published artifacts exist; run the pipeline before releasing")
    target = root / MANIFEST
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render(entries, absent), encoding="utf-8")
    return target, entries, absent
